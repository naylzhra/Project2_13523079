CREATE TABLE shipments (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (order_id),
    shipment_type TEXT NOT NULL CHECK (shipment_type IN ('pickup', 'delivery')),
    shipment_status TEXT NOT NULL CHECK (
        shipment_status IN ('pending', 'in_progress', 'completed')
    ),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (order_id, shipment_type)
);
