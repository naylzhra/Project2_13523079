CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers (customer_id),
    status TEXT NOT NULL CHECK (
        status IN ('waiting_payment', 'pickup', 'processing', 'delivery', 'completed')
    ),
    order_time TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    total_amount BIGINT NOT NULL CHECK (total_amount > 0),
    payment_method TEXT CHECK (payment_method IN ('cash', 'bank_transfer', 'qris')),
    payment_time TIMESTAMPTZ,
    CHECK ((status = 'completed') = (completed_at IS NOT NULL)),
    CHECK ((status = 'waiting_payment') = (payment_time IS NULL)),
    CHECK ((payment_time IS NULL) = (payment_method IS NULL))
);
